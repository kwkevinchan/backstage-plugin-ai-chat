import { randomUUID } from 'node:crypto';
import type { IdGenerator } from '@kwkevinchan/ai-chat-harness';

/** Ids that are random UUIDs, for sessions, runs, leases and tool calls. */
export class UuidGenerator implements IdGenerator {
  next(): string {
    return randomUUID();
  }
}
